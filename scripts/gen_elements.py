#!/usr/bin/env python3
"""Generate crates/trit-chem-core/src/elements_data.rs from a machine-readable table.

Input : data/external/PeriodicTableJSON.json (facts only; see docs/DATA.md)
Output: crates/trit-chem-core/src/elements_data.rs

Oxidation states are curated (CRC Handbook, "Oxidation states of the elements")
because the input JSON has no such field. Predicted values for Z >= 104 are
marked with a trailing '?' in the comment.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "external" / "PeriodicTableJSON.json"
OUT = ROOT / "crates" / "trit-chem-core" / "src" / "elements_data.rs"

KJ_PER_EV = 96.48533212

# Common oxidation states, CRC Handbook 97th ed. table 1. Values for Z >= 104
# are predictions from periodic trends (flagged in the emitted comment).
OX = {
    "H": [-1, 1], "He": [0], "Li": [1], "Be": [2], "B": [3],
    "C": [-4, -3, -2, -1, 1, 2, 3, 4], "N": [-3, -2, -1, 1, 2, 3, 4, 5],
    "O": [-2, -1, 1, 2], "F": [-1], "Ne": [0], "Na": [1], "Mg": [2],
    "Al": [3], "Si": [-4, 4], "P": [-3, 3, 5], "S": [-2, 2, 4, 6],
    "Cl": [-1, 1, 3, 5, 7], "Ar": [0], "K": [1], "Ca": [2], "Sc": [3],
    "Ti": [2, 3, 4], "V": [2, 3, 4, 5], "Cr": [2, 3, 6], "Mn": [2, 3, 4, 6, 7],
    "Fe": [2, 3], "Co": [2, 3], "Ni": [2, 3], "Cu": [1, 2], "Zn": [2],
    "Ga": [3], "Ge": [-4, 2, 4], "As": [-3, 3, 5], "Se": [-2, 4, 6],
    "Br": [-1, 1, 3, 5, 7], "Kr": [0, 2], "Rb": [1], "Sr": [2], "Y": [3],
    "Zr": [4], "Nb": [3, 5], "Mo": [4, 6], "Tc": [4, 7], "Ru": [3, 4],
    "Rh": [3], "Pd": [2, 4], "Ag": [1], "Cd": [2], "In": [3],
    "Sn": [-4, 2, 4], "Sb": [-3, 3, 5], "Te": [-2, 4, 6], "I": [-1, 1, 3, 5, 7],
    "Xe": [0, 2, 4, 6, 8], "Cs": [1], "Ba": [2], "La": [3], "Ce": [3, 4],
    "Pr": [3, 4], "Nd": [3], "Pm": [3], "Sm": [2, 3], "Eu": [2, 3],
    "Gd": [3], "Tb": [3, 4], "Dy": [3], "Ho": [3], "Er": [3], "Tm": [3],
    "Yb": [2, 3], "Lu": [3], "Hf": [4], "Ta": [5], "W": [4, 6], "Re": [4, 6, 7],
    "Os": [4, 8], "Ir": [3, 4], "Pt": [2, 4], "Au": [1, 3], "Hg": [1, 2],
    "Tl": [1, 3], "Pb": [2, 4], "Bi": [3, 5], "Po": [-2, 2, 4], "At": [-1, 1],
    "Rn": [0, 2], "Fr": [1], "Ra": [2], "Ac": [3], "Th": [4], "Pa": [5],
    "U": [3, 4, 5, 6], "Np": [3, 4, 5, 6, 7], "Pu": [3, 4, 5, 6],
    "Am": [3, 4, 5, 6], "Cm": [3, 4], "Bk": [3, 4], "Cf": [3], "Es": [3],
    "Fm": [3], "Md": [3], "No": [2, 3], "Lr": [3], "Rf": [4], "Db": [5],
    "Sg": [6], "Bh": [7], "Hs": [8], "Mt": [3], "Ds": [4], "Rg": [3],
    "Cn": [2], "Nh": [1, 3], "Fl": [2], "Mc": [1, 3], "Lv": [2],
    "Ts": [-1, 1], "Og": [0],
}


def opt(v):
    return "None" if v is None else f"Some({float(v)!r})"


def phase(p):
    p = (p or "").strip().lower()
    return {"gas": "Gas", "liquid": "Liquid", "solid": "Solid"}.get(p, "Unknown")


def main():
    els = [e for e in json.loads(SRC.read_text(encoding="utf-8"))["elements"] if e["number"] <= 118]
    els.sort(key=lambda e: e["number"])
    lines = [
        "// @generated by scripts/gen_elements.py -- do not edit by hand.",
        "// Facts: data/external/PeriodicTableJSON.json; oxidation states: CRC Handbook.",
        "use crate::{Element, Phase};",
        "",
        "pub static ELEMENTS: [Element; 118] = [",
    ]
    for e in els:
        sym = e["symbol"]
        ie = (e.get("ionization_energies") or [None])[0]
        ie_ev = None if ie is None else round(ie / KJ_PER_EV, 4)
        radii = e.get("atomic_radii") or {}
        radius = (radii.get("empirical") or radii.get("calculated") or [None])[0]
        shells = e.get("shells") or []
        outer = shells[-1] if shells else 0
        ox = OX.get(sym, [])
        ox_s = ", ".join(str(v) for v in ox)
        tag = " // predicted" if e["number"] >= 104 else ""
        lines.append(
            f'    Element {{ z: {e["number"]}, symbol: "{sym}", name: "{e["name"]}", '
            f'mass: {float(e["atomic_mass"])!r}, electronegativity: {opt(e.get("electronegativity_pauling"))}, '
            f'first_ie_ev: {opt(ie_ev)}, atomic_radius_pm: {opt(radius)}, '
            f"outer_shell_electrons: {outer}, oxidation_states: &[{ox_s}], "
            f"phase_298: Phase::{phase(e.get('phase'))}, melt_k: {opt(e.get('melt'))}, "
            f"boil_k: {opt(e.get('boil'))}, density_g_cm3: {opt(e.get('density_g_cm3'))}, "
            f"category: \"{e.get('category', 'unknown')}\" }},{tag}"
        )
    lines.append("];")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(els)} elements)")


if __name__ == "__main__":
    main()
