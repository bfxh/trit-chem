#!/usr/bin/env python3
"""Generate crates/trit-chem-core/src/elements_data.rs from elements.json.

Input : data/external/elements.json (built by scripts/fetch_elements.py from
        mendeleev 1.3.0, MIT)
Output: crates/trit-chem-core/src/elements_data.rs

Oxidation states are a curated overlay (common states, CRC Handbook) because
mendeleev's "main" set is sparse for some metals (Cu main = [2] only). The
script asserts that mendeleev's main set is a subset of the overlay, so a typo
in either shows up here.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "external" / "elements.json"
OUT = ROOT / "crates" / "trit-chem-core" / "src" / "elements_data.rs"

OX = {
    "H": [-1, 1], "He": [0], "Li": [1], "Be": [2], "B": [3],
    "C": [-4, -3, -2, -1, 1, 2, 3, 4], "N": [-3, -2, -1, 1, 2, 3, 4, 5],
    "O": [-2, -1, 1, 2], "F": [-1], "Ne": [0], "Na": [1], "Mg": [2],
    "Al": [3], "Si": [-4, 4], "P": [-3, 3, 5], "S": [-2, 2, 4, 6],
    "Cl": [-1, 1, 3, 5, 7], "Ar": [0], "K": [1], "Ca": [2], "Sc": [3],
    "Ti": [2, 3, 4], "V": [2, 3, 4, 5], "Cr": [2, 3, 6], "Mn": [2, 3, 4, 6, 7],
    "Fe": [2, 3], "Co": [2, 3], "Ni": [2, 3], "Cu": [1, 2], "Zn": [2],
    "Ga": [3], "Ge": [-4, 2, 4], "As": [-3, 3, 5], "Se": [-2, 2, 4, 6],
    "Br": [-1, 1, 3, 5, 7], "Kr": [0, 2], "Rb": [1], "Sr": [2], "Y": [3],
    "Zr": [4], "Nb": [3, 5], "Mo": [4, 6], "Tc": [4, 7], "Ru": [3, 4],
    "Rh": [3], "Pd": [2, 4], "Ag": [1], "Cd": [2], "In": [3],
    "Sn": [-4, 2, 4], "Sb": [-3, 3, 5], "Te": [-2, 2, 4, 6], "I": [-1, 1, 3, 5, 7],
    "Xe": [0, 2, 4, 6, 8], "Cs": [1], "Ba": [2], "La": [3], "Ce": [3, 4],
    "Pr": [3, 4], "Nd": [3], "Pm": [3], "Sm": [2, 3], "Eu": [2, 3],
    "Gd": [3], "Tb": [3, 4], "Dy": [3], "Ho": [3], "Er": [3], "Tm": [3],
    "Yb": [2, 3], "Lu": [3], "Hf": [4], "Ta": [5], "W": [4, 6], "Re": [4, 6, 7],
    "Os": [4, 8], "Ir": [3, 4], "Pt": [2, 4], "Au": [1, 3], "Hg": [1, 2],
    "Tl": [1, 3], "Pb": [2, 4], "Bi": [3, 5], "Po": [-2, 2, 4], "At": [-1, 1],
    "Rn": [0, 2], "Fr": [1], "Ra": [2], "Ac": [3], "Th": [4], "Pa": [5],
    "U": [3, 4, 5, 6], "Np": [3, 4, 5, 6, 7], "Pu": [3, 4, 5, 6],
    "Am": [3, 4, 5, 6], "Cm": [3, 4], "Bk": [3, 4], "Cf": [3], "Es": [3],
    "Fm": [3], "Md": [3], "No": [2, 3], "Lr": [3], "Rf": [4], "Db": [5],
    "Sg": [6], "Bh": [7], "Hs": [8], "Mt": [3], "Ds": [4], "Rg": [3],
    "Cn": [2], "Nh": [1, 3], "Fl": [2], "Mc": [1, 3], "Lv": [2],
    "Ts": [-1, 1], "Og": [0],
}

PHASE = {"gas": "Gas", "liquid": "Liquid", "solid": "Solid", "unknown": "Unknown"}


def opt(v, sig=6):
    return "None" if v is None else f"Some({float(f'{float(v):.{sig}g}')!r})"


def main():
    doc = json.loads(SRC.read_text(encoding="utf-8"))
    els = sorted(doc["elements"], key=lambda e: e["z"])
    assert [e["z"] for e in els] == list(range(1, 119)), "need exactly Z=1..118"

    lines = [
        "// @generated by scripts/gen_elements.py -- do not edit by hand.",
        f"// Facts: mendeleev {doc['provenance']['version']} (MIT) via data/external/elements.json;",
        "// oxidation states: curated common states (CRC Handbook), cross-checked against mendeleev.",
        "use crate::{Element, Phase};",
        "",
        "pub static ELEMENTS: [Element; 118] = [",
    ]
    for e in els:
        sym = e["symbol"]
        ox = OX.get(sym, [])
        main = set(e.get("oxidation_states_mendeleev") or [])
        missing = main - set(ox)
        assert not missing, f"{sym}: mendeleev states {sorted(missing)} absent from overlay"
        ox_s = ", ".join(str(v) for v in ox)
        tag = " // predicted" if e["z"] >= 104 else ""
        lines.append(
            f'    Element {{ z: {e["z"]}, symbol: "{sym}", name: "{e["name"]}", '
            f'mass: {float(e["mass"])!r}, electronegativity: {opt(e["electronegativity"])}, '
            f'first_ie_ev: {opt(e["first_ie_ev"])}, atomic_radius_pm: {opt(e["atomic_radius_pm"])}, '
            f"outer_shell_electrons: {e['outer_shell_electrons']}, oxidation_states: &[{ox_s}], "
            f"phase_298: Phase::{PHASE[e['phase_298']]}, melt_k: {opt(e['melt_k'])}, "
            f"boil_k: {opt(e['boil_k'])}, density_g_cm3: {opt(e['density_g_cm3'])}, "
            f'category: "{e["category"]}" }},{tag}'
        )
    lines.append("];")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(els)} elements)")


if __name__ == "__main__":
    main()
